// 「海外」など読みのマップにない値は末尾に回るよう、比較対象がないときは
// 元の漢字表記をそのまま使う（ソートの安定性のためのフォールバックで、
// 呼び出し側で「海外」は別途最後に固定することを想定）。
export function comparePrefecturesByReading(a: string, b: string): number {
  const readingA = PREFECTURE_READINGS[a] ?? a;
  const readingB = PREFECTURE_READINGS[b] ?? b;
  return readingA.localeCompare(readingB, "ja");
}
